def test_blame_missing_file_param(serves):
    status, _payload = get_error("/api/blame", serves["blame"])
    assert status == 400


def test_blame_unknown_file(serves):
    status, payload = get_error("/api/blame?file=nope.py", serves["blame"])
    assert status == 404
    assert payload["error"] == "file not found"


def test_blame_bad_line(serves):
    status, _payload = get_error("/api/blame?file=cart.py&line=zzz", serves["blame"])
    assert status == 400
    status, _payload = get_error("/api/blame?file=cart.py&line=0", serves["blame"])
    assert status == 400


def test_blame_line_out_of_range(serves):
    status, payload = get_error("/api/blame?file=cart.py&line=9999", serves["blame"])
    assert status == 404
    assert "9999" in payload["error"]

def test_health_snapshot(serves):
    data = get_json("/api/health", serves["health"])
    assert data["ok"] is True
    assert data["repo"] == "ledger-demo"
    assert data["initialized"] is True
    assert data["counts"]["total"] >= 1
    assert data["models"]


def test_entries_snapshot(serves):
    data = get_json("/api/entries", serves["entries"])
    assert data["entries"] and data["counts"]["total"] == len(data["entries"])
    first = data["entries"][0]
    assert first["id"].startswith("L-")
    assert isinstance(first["files"], list)


def test_files_snapshot(serves):
    data = get_json("/api/files", serves["files"])
    assert "cart.py" in data["files"]


def test_capsule_snapshot(serves):
    data = get_json("/api/capsule", serves["capsule"])
    assert data["missing"] is False
    assert "CodeLedger capsule" in data["text"]


def test_blame_full_and_single_line(serves):
    full = get_json("/api/blame?file=cart.py", serves["blame"])
    assert full["file"] == "cart.py"
    assert full["lines"]
    ai_lines = [line for line in full["lines"] if line.get("ai")]
    assert ai_lines, "expected at least one AI-authored line in cart.py"
    line_no = ai_lines[0]["no"]
    single = get_json(f"/api/blame?file=cart.py&line={line_no}", serves["blame"])
    assert single["is_ai"] is True
    assert single["line"] == line_no
    assert single["entries"], "an AI line must carry ledger entries"


def test_blame_line_shape(serves):
    """The demo snapshot is fully AI-authored, so assert the payload contract."""
    full = get_json("/api/blame?file=receipt.py", serves["blame"])
    assert len(full["lines"]) >= 1
    for line in full["lines"]:
        assert line["no"] >= 1
        assert isinstance(line["text"], str)
        if line["uncommitted"]:
            assert line["ai"] is False
        else:
            assert line["sha"]
            assert isinstance(line["entry_ids"], list)


def test_post_is_read_only(serves):
    request = urllib.request.Request(
        f"http://127.0.0.1:{serves['blame']}/api/blame",
        data=b"{}", method="POST", headers={"Content-Type": "application/json"},
    )
    with pytest.raises(urllib.error.HTTPError) as exc_info:
        urllib.request.urlopen(request, timeout=15)
    assert exc_info.value.code == 405



"""The Vercel serverless functions in ``api/``: same payloads as the local
``ledger ui`` API, served from snapshots generated by ``tools/gen_vercel_data.py``
from the ledger-demo repository (``git`` cannot run inside the function).
"""
from __future__ import annotations

import importlib.util
import json
import threading
import urllib.error
import urllib.request
from http.server import ThreadingHTTPServer
from pathlib import Path
from types import ModuleType

import pytest

API_DIR = Path(__file__).resolve().parents[1] / "api"
NAMES = ("health", "entries", "blame", "files", "capsule")


def _load(name: str) -> ModuleType:
    """Import ``api/<name>.py`` the way the Vercel runtime does: as a file."""
    spec = importlib.util.spec_from_file_location(f"api_{name}", API_DIR / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


@pytest.fixture
def serves():
    """Each function bound to its own loopback server; yields {name: port}."""
    modules = {name: _load(name) for name in NAMES}
    servers = {
        name: ThreadingHTTPServer(("127.0.0.1", 0), module.handler)
        for name, module in modules.items()
    }
    threads = []
    for server in servers.values():
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        threads.append(thread)
    yield {name: server.server_address[1] for name, server in servers.items()}
    for server in servers.values():
        server.shutdown()
        server.server_close()


def get(path: str, port: int):
    return urllib.request.urlopen(f"http://127.0.0.1:{port}{path}", timeout=15)


def get_json(path: str, port: int) -> dict:
    with get(path, port) as response:
        assert response.status == 200
        return json.loads(response.read().decode("utf-8"))


def get_error(path: str, port: int) -> tuple:
    """Expected error: returns (status, {'error': ...})."""
    with pytest.raises(urllib.error.HTTPError) as exc_info:
        get(path, port)
    response = exc_info.value
    payload = json.loads(response.read().decode("utf-8"))
    assert isinstance(payload.get("error"), str) and payload["error"]
    assert response.headers.get("Content-Type", "").startswith("application/json")
    return response.code, payload



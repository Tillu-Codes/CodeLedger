"""Vercel function: ``GET /api/blame`` — ``?file=<path>`` and optional ``&line=<n>``.

Without ``line``: the full per-line annotation payload (one precomputed
``codeledger.webui.api_blame_full`` snapshot).  With ``line``: the single-line
``reveal`` story (prompt/model/tool that produced the line).  Both were
generated by ``tools/gen_vercel_data.py`` from ledger-demo, since ``git``
cannot run inside the function.
"""
from __future__ import annotations

import json
from http.server import BaseHTTPRequestHandler
from pathlib import Path
from typing import Any, Dict
from urllib.parse import parse_qs, urlparse

_DATA: Dict[str, Any] = json.loads(
    (Path(__file__).resolve().parent / "data" / "blame.json").read_text(encoding="utf-8")
)


def _respond(h: BaseHTTPRequestHandler, payload: Dict[str, Any], status: int = 200) -> None:
    body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    h.send_response(status)
    h.send_header("Content-Type", "application/json; charset=utf-8")
    h.send_header("Content-Length", str(len(body)))
    h.send_header("Cache-Control", "no-store")
    h.end_headers()
    if h.command != "HEAD":
        h.wfile.write(body)


class handler(BaseHTTPRequestHandler):
    server_version = "CodeLedger"
    sys_version = ""

    def do_GET(self) -> None:
        parsed = urlparse(self.path)
        query: Dict[str, str] = {}
        for key, values in parse_qs(parsed.query, keep_blank_values=True).items():
            query[key.lower()] = values[0]
        file_name = query.get("file", "").strip()
        if not file_name:
            _respond(self, {"error": "missing ?file= parameter"}, 400)
            return
        record = _DATA.get(file_name)
        if record is None:
            _respond(self, {"error": "file not found"}, 404)
            return
        if record.get("error"):
            _respond(self, {"error": str(record["error"])}, 400)
            return
        line = query.get("line", "").strip()
        if line:
            if not line.isdigit() or int(line) < 1:
                _respond(self, {"error": "?line= must be a positive integer"}, 400)
                return
            payload = record["lines"].get(str(int(line)))
            if payload is None:
                _respond(
                    self, {"error": f"no blame snapshot for {file_name}:{line}"}, 404
                )
                return
            if isinstance(payload, dict) and payload.get("error"):
                _respond(self, {"error": str(payload["error"])}, 400)
                return
            _respond(self, payload)
        else:
            _respond(self, record["full"])

    def do_HEAD(self) -> None:
        _respond(self, {})

    def do_POST(self) -> None:
        _respond(self, {"error": "the CodeLedger UI is read-only"}, 405)

    def log_message(self, *args: object) -> None:
        """Keep the function logs calm."""
